const projectModal = document.getElementById("projectModal");
const modalClose = document.getElementById("modalClose");
const modalContent = document.getElementById("modalContent");

let currentGallery = [];
let currentIndex = 0;

function renderGallery(title, images) {
    currentGallery = images;
    currentIndex = 0;

    modalContent.innerHTML = `
    <h2 style="color:white; text-align:center; margin-bottom:20px;">${title}</h2>

    <div class="gallery-slider">
      <button class="gallery-btn prev" id="prevBtn">
        <i class="fas fa-chevron-left"></i>
      </button>

      <img id="galleryImage" src="${currentGallery[currentIndex]}" class="gallery-image" />

      <button class="gallery-btn next" id="nextBtn">
        <i class="fas fa-chevron-right"></i>
      </button>
    </div>

    <div class="gallery-dots" id="galleryDots"></div>
  `;

    updateDots();

    document.getElementById("prevBtn").addEventListener("click", () => {
        currentIndex = (currentIndex - 1 + currentGallery.length) % currentGallery.length;
        updateImage();
    });

    document.getElementById("nextBtn").addEventListener("click", () => {
        currentIndex = (currentIndex + 1) % currentGallery.length;
        updateImage();
    });
}

function updateImage() {
    document.getElementById("galleryImage").src = currentGallery[currentIndex];
    updateDots();
}

function updateDots() {
    const dotsContainer = document.getElementById("galleryDots");
    dotsContainer.innerHTML = "";

    currentGallery.forEach((img, index) => {
        const dot = document.createElement("div");
        dot.classList.add("gallery-dot");

        if (index === currentIndex) dot.classList.add("active");

        dot.addEventListener("click", () => {
            currentIndex = index;
            updateImage();
        });

        dotsContainer.appendChild(dot);
    });
}

function openModal() {
    projectModal.classList.add("active");
}

function closeModal() {
    projectModal.classList.remove("active");
}

modalClose.addEventListener("click", closeModal);

projectModal.addEventListener("click", (e) => {
    if (e.target === projectModal) closeModal();
});

document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") closeModal();
});

document.querySelectorAll(".open-gallery").forEach(btn => {
    btn.addEventListener("click", (e) => {
        e.preventDefault();

        const title = btn.getAttribute("data-title");
        const images = btn.getAttribute("data-images").split(",").map(img => img.trim());

        renderGallery(title, images);
        openModal();
    });
});